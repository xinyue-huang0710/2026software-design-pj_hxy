import {execFileSync,spawnSync} from 'node:child_process';
import {mkdirSync,writeFileSync,readFileSync,mkdtempSync,readdirSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {tmpdir} from 'node:os';
const root=resolve(import.meta.dirname,'..'), snapshot=join(root,'tmp','phase1-final');
mkdirSync(snapshot,{recursive:true});
const tar=join(root,'tmp','phase1-final.tar');
execFileSync('git',['archive','final','-o',tar],{cwd:root});
execFileSync('tar',['-xf',tar,'-C',snapshot]);
if(!existsSync(join(snapshot,'node_modules'))) {
  // Junction is local to the ignored snapshot; it reuses locked dependencies.
  const {symlinkSync}=await import('node:fs');
  symlinkSync(join(root,'node_modules'),join(snapshot,'node_modules'),'junction');
}
const output=join(root,'doc','transcript','phase1');
mkdirSync(output,{recursive:true});
for(const name of ['session','flowchart']){
  const cwd=mkdtempSync(join(tmpdir(),'svg-p1-'));
  mkdirSync(join(cwd,'examples'));
  for(const file of readdirSync(join(snapshot,'examples'))) writeFileSync(join(cwd,'examples',file),readFileSync(join(snapshot,'examples',file)));
  const input=readFileSync(join(snapshot,'examples',name+'.txt'),'utf8');
  const run=spawnSync(process.execPath,[join(root,'node_modules','tsx','dist','cli.mjs'),join(snapshot,'src','main.ts')],{cwd,input,encoding:'utf8'});
  if(run.status!==0)throw Error(run.stderr);
  writeFileSync(join(output,name+'.txt'),input);
  writeFileSync(join(output,name+'.expected.txt'),run.stdout);
  writeFileSync(join(output,name+'.expected.svg'),readFileSync(join(cwd,'examples',name==='session'?'demo.svg':'flowchart.svg')));
}
writeFileSync(join(output,'baseline.json'),JSON.stringify({ref:'final',commit:execFileSync('git',['rev-parse','final^{}'],{cwd:root,encoding:'utf8'}).trim(),description:'Generated by executing immutable final source; inputs contain only commands/comments.'},null,2)+'\n');
console.log('Captured immutable final transcripts.');
